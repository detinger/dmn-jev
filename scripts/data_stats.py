"""Descriptive statistics of the CFPB corpus and sample -> paper/generated/data_numbers.tex.

These numbers do not depend on any model run.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import pandas as pd


def fmt_int(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def main() -> None:
    corpus = pd.read_parquet("data/interim/cfpb_corpus.parquet")
    sample = pd.read_parquet("data/interim/cfpb_sample.parquet")
    banking = corpus[corpus.product_group.isin(["bank_account", "card", "money_transfer"])]
    relief = sample[sample.in_relief]
    routing = sample[sample.in_routing]
    n = {
        "corpus": fmt_int(len(corpus)),
        "banking": fmt_int(len(banking)),
        "bankingrelief": f"{100 * (banking.relief == 'relief').mean():.1f}\\%",
        "labelchanged": f"{100 * corpus.label_changed.mean():.2f}\\%",
        "sample": fmt_int(len(sample)),
        "reliefn": fmt_int(len(relief)),
        "routingn": fmt_int(len(routing)),
        "reliefpos": f"{100 * (relief.relief == 'relief').mean():.1f}\\%",
        "wordsmedian": f"{sample.n_words.median():.0f}",
        "wordsiqr": f"{sample.n_words.quantile(0.25):.0f}--{sample.n_words.quantile(0.75):.0f}",
        "truncated": fmt_int(int((sample.n_words > 1500).sum())),
        "fraudcorpus": fmt_int(int((corpus.queue == "fraud").sum())),
    }
    for split in ("pool", "calibration", "test"):
        n[f"relief{split}"] = fmt_int(int((relief.split_relief == split).sum()))
        n[f"routing{split}"] = fmt_int(int((routing.split_routing == split).sum()))
    queue = routing.queue.value_counts().to_dict()
    for q, c in queue.items():
        n[f"queue.{q}"] = fmt_int(c)

    out = Path("paper/generated")
    out.mkdir(parents=True, exist_ok=True)
    lines = ["% Generated by scripts/data_stats.py -- do not edit."]
    lines += [rf"\expandafter\def\csname res@data.{k}\endcsname{{{v}}}" for k, v in sorted(n.items())]
    (out / "data_numbers.tex").write_text("\n".join(lines) + "\n")

    manifest = {
        "mirror_sha256": Path("data/raw/hf_cfpb/SHA256SUMS").read_text().split("\n")[:11],
        "official_zip_sha256": Path("data/raw/complaints.csv.zip.sha256").read_text().split()[0],
        "sample_ids_sha256": hashlib.sha256(",".join(map(str, sample.complaint_id)).encode()).hexdigest(),
        "counts": {k: v.replace("{,}", ",").replace("\\%", "%") for k, v in n.items()},
    }
    Path("results").mkdir(exist_ok=True)
    path = Path("results/data_manifest.json")
    # Keep fields written by other steps (e.g. the frozen question schema hash).
    old = json.loads(path.read_text()) if path.exists() else {}
    path.write_text(json.dumps({**old, **manifest}, indent=2))
    sample[["complaint_id", "in_relief", "in_routing", "split_relief", "split_routing", "relief", "queue"]].to_csv(
        "results/sample_ids.csv", index=False)
    print(json.dumps(manifest["counts"], indent=1))


if __name__ == "__main__":
    main()
