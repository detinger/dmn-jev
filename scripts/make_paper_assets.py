def pct(x, d=1):
    return f"{100 * x:.{d}f}\\%"


def num(x, d=3):
    return f"{x:.{d}f}"


class Numbers:
    def __init__(self):
        self.items: dict[str, str] = {}

    def __setitem__(self, k, v):
        self.items[k] = v

    def write(self, path: Path, simulated: bool):
        lines = ["% Generated by scripts/make_paper_assets.py -- do not edit."]
        if simulated:
            lines.append(r"\def\SimulatedResults{1}")
        for k, v in sorted(self.items.items()):
            lines.append(rf"\expandafter\def\csname res@{k}\endcsname{{{v}}}")
        path.write_text("\n".join(lines) + "\n")


def load(root: Path, task: str) -> dict:
    d = root / task
    return {"summary": json.loads((d / "summary.json").read_text()),
            "gates": pd.read_csv(d / "gates.csv"), "curve": pd.read_csv(d / "complexity_curve.csv"),
            "rel_raw": pd.read_csv(d / "reliability_raw.csv"), "rel_iso": pd.read_csv(d / "reliability_iso.csv"),
            "rc_conf": pd.read_csv(d / "risk_coverage_jev_confidence.csv"),
            "rc_learned": pd.read_csv(d / "risk_coverage_learned.csv"),
            "lc": pd.read_csv(d / "learning_curves.csv"), "business": pd.read_csv(d / "table_business.csv", dtype=str, keep_default_na=False),
            "gate_table": pd.read_csv(d / "table_gate.csv", dtype=str, keep_default_na=False),
            "gates_sup": pd.read_csv(d / "gates_sup.csv")}


def numbers_for(n: Numbers, task: str, r: dict) -> None:
    s = r["summary"]
    dist, base, cal = s["distillation"], s["baselines"], s["calibration"]["holistic_test"]
    p = f"{task}."
    n[p + "cases"] = f"{s['n_cases']:,}".replace(",", "{,}")
    n[p + "test"] = f"{s['splits'].get('test', 0):,}".replace(",", "{,}")
    n[p + "pool"] = f"{s['splits'].get('pool', 0):,}".replace(",", "{,}")
    n[p + "calibration"] = f"{s['splits'].get('calibration', 0):,}".replace(",", "{,}")
    n[p + "rules"] = str(dist["n_rules"])
    n[p + "inputs"] = str(dist["n_inputs"])
    n[p + "meancond"] = num(dist["mean_conditions"], 2)
    n[p + "fidelity"] = pct(dist["fidelity_test"]["agreement"])
    lo, hi = dist["fidelity_ci"][1], dist["fidelity_ci"][2]
    n[p + "fidelityci"] = f"[{100 * lo:.1f}, {100 * hi:.1f}]"
    n[p + "kappa"] = num(dist["fidelity_test"]["kappa"], 3)
    n[p + "accdmn"] = pct(base["dmn_distil"]["accuracy"])
    n[p + "accjev"] = pct(base["jev_holistic"]["accuracy"])
    n[p + "f1dmn"] = num(base["dmn_distil"]["macro_f1"], 3)
    n[p + "f1jev"] = num(base["jev_holistic"]["macro_f1"], 3)
    n[p + "accmajority"] = pct(base["majority_class"]["accuracy"])
    n[p + "mcnemarp"] = f"{base['mcnemar_dmn_vs_jev']['p_value']:.3g}"
    n[p + "ece"] = num(cal["ece"], 3)
    n[p + "eceiso"] = num(cal.get("ece_isotonic", float("nan")), 3)
    n[p + "brier"] = num(cal["brier"], 3)
    n[p + "meanconf"] = pct(cal["mean_confidence"])
    n[p + "accholistic"] = pct(cal["accuracy"])
    g = s["gate"]
    n[p + "agreerate"] = pct(g["agreement_rate_test"])
    n[p + "accagree"] = pct(g["accuracy_when_agree"])
    n[p + "accdisagree"] = pct(g["accuracy_when_disagree"])
    n[p + "aurcconf"] = num(g["aurc"]["jev_confidence"], 3)
    n[p + "aurclearned"] = num(g["aurc"]["learned"], 3)
    for v in g["validity"]:
        n[p + f"violation{int(round(100 * v['eps']))}"] = pct(v["violation_rate"])
    for tag, gates in (("", r["gates"]), ("sup", r["gates_sup"])):
        for _, row in gates.iterrows():
            key = f"{p}{tag}{row['gate']}{'A' if row['agreement'] else ''}.{int(round(100 * row['eps']))}"
            n[key + ".cov"] = pct(row["coverage"])
            n[key + ".risk"] = pct(row["selective_risk"])
            if "miss_rate" in row and pd.notna(row["miss_rate"]):
                n[key + ".miss"] = pct(row["miss_rate"])
    for name, m in (("dmn", base["dmn_distil"]), ("jev", base["jev_holistic"]), ("sup", s["dmn_sup"]["accuracy_test"]),
                    ("majority", base["majority_class"])):
        n[p + f"bacc{name}"] = pct(m["balanced_accuracy"])
        if "recall_pos" in m:
            n[p + f"recall{name}"] = pct(m["recall_pos"])
            n[p + f"precision{name}"] = pct(m["precision_pos"])
    n[p + "accsup"] = pct(s["dmn_sup"]["accuracy_test"]["accuracy"])
    n[p + "rulessup"] = str(s["dmn_sup"]["n_rules"])
    n[p + "inputssup"] = str(s["dmn_sup"]["n_inputs"])
    n[p + "agreesup"] = pct(s["dmn_sup"]["agreement_with_jev_test"])
    if s["gate"].get("critical_class"):
        n[p + "posrate"] = pct(s["class_balance"][s["gate"]["critical_class"]])
        n[p + "critical"] = s["gate"]["critical_class"].replace("_", r"\_")
    v = s["verification"]
    n[p + "rulesraw"] = str(v["before_merge"]["n_rules"])
    n[p + "rulesfirst"] = str(v["first_hit"]["n_rules"])
    n[p + "conflicts"] = str(v["after_merge"]["overlaps_conflicting"])
    n[p + "gaps"] = str(v["after_merge"]["gap_boxes"])
    n[p + "roundtrip"] = pct(s["xml_roundtrip_agreement"])
    o = s["operational"]
    n[p + "latmed"] = f"{o['jev_latency_ms_median']:.0f}"
    n[p + "latp95"] = f"{o['jev_latency_ms_p95']:.0f}"
    n[p + "dmnus"] = f"{o['dmn_eval_us_per_case']:.1f}"
    n[p + "cost"] = f"{o['cost_usd_per_1000']:.4f}"
    n[p + "tokens"] = f"{o['input_tokens_mean']:.0f}"
    n[p + "review"] = f"{o['review_per_1000']:.0f}"
    n[p + "models"] = ", ".join(s["models"])
    lc = r["lc"]
    full = lc[lc["labels"] == lc["labels"].max()]
    for m, tag in (("DMN-Sup", "sup"), ("TF-IDF+LR", "tfidf")):
        n[p + f"acc{tag}full"] = pct(full[full.method == m]["accuracy"].mean())
        n[p + f"f1{tag}full"] = num(full[full.method == m]["macro_f1"].mean(), 3)
    n[p + "labelsfull"] = f"{int(lc['labels'].max()):,}".replace(",", "{,}")


