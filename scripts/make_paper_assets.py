def tab_main(results: dict, out: Path) -> None:
    rows = []
    for t, r in results.items():
        s = r["summary"]
        d, b, v = s["distillation"], s["baselines"], s["verification"]
        rows.append(
            f"{TASKS[t]} & {v['before_merge']['n_rules']} & {d['n_rules']} & {v['first_hit']['n_rules']} & {d['n_inputs']} & "
            f"{d['mean_conditions']:.2f} & {100 * d['fidelity_test']['agreement']:.1f} "
            f"[{100 * d['fidelity_ci'][1]:.1f}, {100 * d['fidelity_ci'][2]:.1f}] & {d['fidelity_test']['kappa']:.3f} & "
            f"{v['after_merge']['overlaps_conflicting']}/{v['after_merge']['gap_boxes']} \\\\")
    out.write_text("\n".join([
        r"\begin{tabular}{@{}lrrrrrlrr@{}}", r"\toprule",
        r" & \multicolumn{3}{c}{Rules} & & & & & \\ \cmidrule(lr){2-4}",
        r"Task & Tree & Merged & FIRST & Inputs & Cond./rule & Fidelity (\%) [95\% CI] & $\kappa$ & Overl./gaps \\",
        r"\midrule", *rows, r"\bottomrule", r"\end{tabular}"]) + "\n")


def tab_calibration(results: dict, out: Path) -> None:
    rows = []
    for t, r in results.items():
        c, cc = r["summary"]["calibration"]["holistic_test"], r["summary"]["calibration"]["holistic_calib"]
        rows.append(f"{TASKS[t]} & {100 * c['accuracy']:.1f} & {100 * c['mean_confidence']:.1f} & {c['ece']:.3f} & "
                    f"{c['ece_quantile']:.3f} & {c['mce']:.3f} & {c['brier']:.3f} & {c.get('ece_isotonic', float('nan')):.3f} \\\\")
    out.write_text("\n".join([
        r"\begin{tabular}{@{}lrrrrrrr@{}}", r"\toprule",
        r"Task & Acc. (\%) & Mean conf. (\%) & ECE & ECE$_{\mathrm{q}}$ & MCE & Brier & ECE (isotonic) \\",
        r"\midrule", *rows, r"\bottomrule", r"\end{tabular}"]) + "\n")


def tab_gate(results: dict, out: Path, eps=(0.05, 0.10)) -> None:
    """Coverage, selective risk and critical-class miss rate on the test set ('--' = nothing certified)."""
    labels = [("gates", "jev_confidence", True, "Jev confidence"), ("gates", "learned", True, "Learned gate"),
              ("gates_sup", "learned", True, "Learned gate, DMN-Sup")]
    lines = [r"\begin{tabular}{@{}ll" + "rrr" * len(eps) + "@{}}", r"\toprule",
             " & & " + " & ".join(rf"\multicolumn{{3}}{{c}}{{$\varepsilon={e:g}$}}" for e in eps) + r" \\",
             "".join(rf"\cmidrule(lr){{{3 + 3 * k}-{5 + 3 * k}}}" for k in range(len(eps))),
             "Task & Gate (with agreement filter) & " + " & ".join(["Cov. & Risk & Miss"] * len(eps)) + r" \\",
             r"\midrule"]
    for t, r in results.items():
        for k, (src, gname, agree, lab) in enumerate(labels):
            g = r[src]
            cells = []
            for e in eps:
                row = g[(g.gate == gname) & (g.agreement == agree) & np.isclose(g.eps, e)].iloc[0]
                auto = row.n_auto > 0
                miss = row.get("miss_rate", np.nan)
                cells += [f"{100 * row.coverage:.1f}", f"{100 * row.selective_risk:.1f}" if auto else "--",
                          (f"{100 * miss:.1f}" if auto else "--") if pd.notna(miss) else "n/a"]
            lines.append(f"{TASKS[t] if k == 0 else ''} & {lab} & " + " & ".join(cells) + r" \\")
        lines.append(r"\midrule")
    lines[-1] = r"\bottomrule"
    lines.append(r"\end{tabular}")
    out.write_text("\n".join(lines) + "\n")


def tab_baselines(results: dict, out: Path) -> None:
    lines = [r"\begin{tabular}{@{}llrrrrc@{}}", r"\toprule",
             r"Task & Method & Labels & Acc. (\%) & Bal. acc. (\%) & Recall$_+$ (\%) & Auditable logic \\", r"\midrule"]
    for t, r in results.items():
        s, b, lc = r["summary"], r["summary"]["baselines"], r["lc"]
        full = lc[lc["labels"] == lc["labels"].max()]
        nfull = f"{int(lc['labels'].max()):,}"
        mean = lambda m: {k: full[full.method == m][k].mean() for k in full.columns  # noqa: E731
                          if k in ("accuracy", "balanced_accuracy", "recall_pos")}
        rows = [("Majority class", nfull, b["majority_class"], "--"),
                ("Jev holistic", "0", b["jev_holistic"], "no"),
                ("Jev + DMN, distilled (ours)", "0", b["dmn_distil"], "yes"),
                ("Jev + DMN, supervised (DMN-Sup)", nfull, s["dmn_sup"]["accuracy_test"], "yes"),
                ("TF-IDF + logistic regression", nfull, mean("TF-IDF+LR"), "no")]
        for k, (name, labels, m, aud) in enumerate(rows):
            rec = f"{100 * m['recall_pos']:.1f}" if "recall_pos" in m and pd.notna(m.get("recall_pos")) else "--"
            lines.append(f"{TASKS[t] if k == 0 else ''} & {name} & {labels} & {100 * m['accuracy']:.1f} & "
                         f"{100 * m['balanced_accuracy']:.1f} & {rec} & {aud} \\\\")
        lines.append(r"\midrule")
    lines[-1] = r"\bottomrule"
    lines.append(r"\end{tabular}")
    out.write_text("\n".join(lines) + "\n")


def tab_rules(r: dict, out: Path, max_rules: int = 14) -> None:
    df = r["business"]
    df = df.loc[:, (df != "-").any(axis=0)]
    cols = [c for c in df.columns if c not in ("support", "purity")]
    body = df.head(max_rules)
    esc = lambda s: str(s).replace("_", r"\_").replace("&", r"\&").replace('"', "''")  # noqa: E731
    lines = [r"\begin{tabular}{@{}r" + "l" * len(cols) + "r@{}}", r"\toprule",
             "\\# & " + " & ".join(esc(c) for c in cols) + r" & Support \\", r"\midrule"]
    for k, (_, row) in enumerate(body.iterrows(), 1):
        lines.append(f"{k} & " + " & ".join(r"\texttt{" + esc(row[c]) + "}" for c in cols) + f" & {int(row['support'])} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    out.write_text("\n".join(lines) + "\n")


# Figures -----------------------------------------------------------------------------------

def _two_panels(width=7.0, height=2.6, n=len(TASKS)):
    fig, axes = plt.subplots(1, n, figsize=(width, height), layout="constrained")
    fig.get_layout_engine().set(w_pad=0.08, wspace=0.08)
    return fig, axes


def _log_x(ax):
    ax.set_xscale("log")
    ax.xaxis.set_major_locator(LogLocator(base=10, subs=(1.0,)))
    ax.xaxis.set_major_formatter(FuncFormatter(lambda v, _: f"{v:,.0f}"))
    ax.xaxis.set_minor_formatter(NullFormatter())


def fig_complexity(results: dict, out: Path) -> None:
    fig, axes = _two_panels()
    for ax, (t, r) in zip(axes, results.items()):
        c = r["curve"].sort_values("n_rules_full")
        ax.scatter(c["n_rules_full"], 100 * c["test_fidelity"], s=14, color=BLUE, edgecolor="white", linewidth=0.6,
                   label="Configuration", zorder=3)
        front = c.loc[c["test_fidelity"].cummax().drop_duplicates().index]
        ax.step(front["n_rules_full"], 100 * front["test_fidelity"], where="post", color=INK, linewidth=1.0,
                label="Pareto front")
        chosen = r["summary"]["distillation"]
        ax.scatter([chosen["n_rules"]], [100 * chosen["fidelity_test"]["agreement"]], s=40, marker="D",
                   color=ORANGE, edgecolor="white", linewidth=0.8, label="Selected table", zorder=4)
        _log_x(ax)
        ax.set_xlabel("Rules in the table (log scale)")
        ax.set_ylabel("Fidelity to Jev on test set (%)")
        ax.set_title(TASKS[t], loc="left", color=INK)
    axes[0].legend(frameon=False, loc="lower right")
    for ax in axes[1:]:
        ax.set_ylabel("")
    fig.savefig(out)
    plt.close(fig)


def fig_reliability(results: dict, out: Path) -> None:
    fig, axes = _two_panels(height=2.8)
    for ax, (t, r) in zip(axes, results.items()):
        ax.plot([0, 1], [0, 1], color=MUTED, linewidth=0.8, linestyle=(0, (1, 2)), label="Perfect calibration")
        for df, col, mk, ls, lab in ((r["rel_raw"], BLUE, "o", "-", "Jev (raw)"),
                                     (r["rel_iso"], ORANGE, "s", "--", "Isotonic")):
            df = df[df["n"] >= 10]
            ax.plot(df["confidence"], df["accuracy"], color=col, linestyle=ls, marker=mk, markersize=4,
                    markeredgecolor="white", markeredgewidth=0.6, label=lab)
        ax.set_xlim(0, 1.0)
        ax.set_ylim(0, 1.0)
        ax.set_xlabel("Top-label confidence")
        ax.set_ylabel("Observed accuracy")
        ax.set_title(TASKS[t], loc="left", color=INK)
    axes[0].legend(frameon=False, loc="upper left")
    for ax in axes[1:]:
        ax.set_ylabel("")
    fig.savefig(out)
    plt.close(fig)


def fig_risk_coverage(results: dict, out: Path, eps_marks=(0.02, 0.05, 0.10)) -> None:
    fig, axes = _two_panels(height=2.8)
    for ax, (t, r) in zip(axes, results.items()):
        for df, col, ls, lab in ((r["rc_conf"], BLUE, "-", "Jev confidence"), (r["rc_learned"], ORANGE, "--", "Learned gate")):
            ax.plot(100 * df["coverage"], 100 * df["risk"], color=col, linestyle=ls, label=lab)
        top = max(df.loc[df["coverage"] >= 0.05, "risk"].max() for df in (r["rc_conf"], r["rc_learned"]))
        top = 100 * max(top, max(eps_marks)) * 1.15
        for e in eps_marks:
            ax.axhline(100 * e, color=MUTED, linewidth=0.6)
            ax.text(99, 100 * e + 0.012 * top, rf"$\varepsilon$ = {e:g}", ha="right", va="bottom", fontsize=6.5, color=MUTED)
        ax.set_xlim(0, 100)
        ax.set_ylim(0, top)
        ax.set_xlabel("Cases automated (%)")
        ax.set_ylabel("Error rate among automated cases (%)")
        ax.set_title(TASKS[t], loc="left", color=INK)
    axes[0].legend(frameon=False, loc="upper left")
    for ax in axes[1:]:
        ax.set_ylabel("")
    fig.savefig(out)
    plt.close(fig)


def fig_learning(results: dict, out: Path) -> None:
    fig, axes = _two_panels(height=2.8)
    for ax, (t, r) in zip(axes, results.items()):
        lc, b = r["lc"], r["summary"]["baselines"]
        for m, col, mk, ls in (("DMN-Sup", BLUE, "o", "-"), ("TF-IDF+LR", ORANGE, "s", "--")):
            g = lc[lc.method == m].groupby("labels")["balanced_accuracy"].agg(["mean", "std"]).reset_index()
            ax.errorbar(g["labels"], 100 * g["mean"], yerr=100 * g["std"].fillna(0), color=col, marker=mk,
                        linestyle=ls, markersize=4, markeredgecolor="white", markeredgewidth=0.6, capsize=2,
                        elinewidth=0.8, label={"DMN-Sup": "Jev + DMN, supervised", "TF-IDF+LR": "TF-IDF + LR"}[m])
        ax.axhline(100 * b["dmn_distil"]["balanced_accuracy"], color=AQUA, linewidth=1.4, label="Jev + DMN, distilled (0 labels)")
        ax.axhline(100 * b["jev_holistic"]["balanced_accuracy"], color=INK, linewidth=0.9, linestyle=(0, (4, 2)),
                   label="Jev holistic (0 labels)")
        _log_x(ax)
        ax.set_xlabel("Training labels (log scale)")
        ax.set_ylabel("Balanced accuracy on test set (%)")
        ax.set_title(TASKS[t], loc="left", color=INK)
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, frameon=False, loc="outside lower center", ncol=4)
    for ax in axes[1:]:
        ax.set_ylabel("")
    fig.savefig(out)
    plt.close(fig)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--extractor", choices=["jev", "simulated"], required=True)
    args = ap.parse_args()
    simulated = args.extractor == "simulated"
    root = Path("results") / args.extractor
    out = Path("paper") / ("generated_sim" if simulated else "generated")
    out.mkdir(parents=True, exist_ok=True)

    results = {t: load(root, t) for t in TASKS if (root / t / "summary.json").exists()}
    n = Numbers()
    for t, r in results.items():
        numbers_for(n, t, r)
    n.write(out / "numbers.tex", simulated)
    tab_main(results, out / "tab_distillation.tex")
    tab_calibration(results, out / "tab_calibration.tex")
    tab_gate(results, out / "tab_gate.tex")
    tab_baselines(results, out / "tab_baselines.tex")
    if "relief" in results:
        tab_rules(results["relief"], out / "tab_rules_relief.tex")
    fig_complexity(results, out / "fig_complexity.pdf")
    fig_reliability(results, out / "fig_reliability.pdf")
    fig_risk_coverage(results, out / "fig_risk_coverage.pdf")
    fig_learning(results, out / "fig_learning.pdf")
    print(f"wrote {len(n.items)} numbers and assets to {out}")


if __name__ == "__main__":
    main()
