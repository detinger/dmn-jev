"""Generate the numbers, tables and figures that the manuscript includes.

    python scripts/make_paper_assets.py --extractor jev         # -> paper/generated/
    python scripts/make_paper_assets.py --extractor simulated   # -> paper/generated_sim/ (layout check only)

Every number in the results section of the paper comes from here, through the
\\res{key} macro. Simulated runs are written to a separate directory and are
watermarked, so they can never end up in the manuscript by accident.
"""

